#!/usr/bin/env node
// Batch 74 — KARC-001/009/010/011, KQA-001: generates docs/architecture.md from the source tree (no invented content).
// Usage: node backend/scripts/gen-arch-docs.mjs   (run from repo root or backend/)
import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { join, resolve } from "node:path";
const root = existsSync("backend/src") ? resolve(".") : resolve("..");
const B = join(root, "backend");
const ls = (d, ext) => (existsSync(d) ? readdirSync(d).filter((f) => f.endsWith(ext)).sort() : []);
const read = (p) => readFileSync(p, "utf8");

// Route modules → mount path (from index.ts) and route count
const index = read(join(B, "src/index.ts"));
const mounts = [...index.matchAll(/app\.use\("(\/api[^"]*)",\s*(?:[a-zA-Z]+,\s*)*([A-Za-z0-9]+Router)/g)].map((m) => [m[1], m[2]]);
const imports = Object.fromEntries([...index.matchAll(/import \{ ([A-Za-z0-9]+Router)[^}]*\} from "\.\/routes\/([^"]+)\.js"/g)].map((m) => [m[1], m[2]]));
const routeRows = ls(join(B, "src/routes"), ".ts").map((f) => {
  const src = read(join(B, "src/routes", f));
  const n = (src.match(/[A-Za-z0-9]+Router\.(get|post|put|patch|delete)\(/g) ?? []).length;
  const mount = mounts.filter(([, r]) => imports[r] === f.replace(/\.ts$/, "")).map(([p]) => p).join(", ");
  return { f, n, mount: mount || "—" };
});

// Lib dependencies: which routes import which libs
const libs = ls(join(B, "src/lib"), ".ts");
const usedBy = Object.fromEntries(libs.map((l) => [l, []]));
for (const r of routeRows) {
  const src = read(join(B, "src/routes", r.f));
  for (const m of src.matchAll(/from "\.\.\/lib\/([a-z0-9-]+)\.js"/g)) if (usedBy[m[1] + ".ts"] && !usedBy[m[1] + ".ts"].includes(r.f)) usedBy[m[1] + ".ts"].push(r.f);
}

// DB models
const schema = read(join(B, "prisma/schema.prisma"));
const models = [...schema.matchAll(/^model (\w+) \{([\s\S]*?)^\}/gm)].map((m) => ({ name: m[1], fields: (m[2].match(/^\s+\w+\s+\S+/gm) ?? []).filter((l) => !/^\s+@@/.test(l)).length, rels: (m[2].match(/@relation/g) ?? []).length }));
const enums = [...schema.matchAll(/^enum (\w+)/gm)].map((m) => m[1]);

// Tests
const tests = [...ls(join(B, "tests"), ".test.ts").map((f) => `tests/${f}`), ...ls(join(B, "tests/db"), ".test.ts").map((f) => `tests/db/${f}`)];
const testRows = tests.map((f) => [f, (read(join(B, f)).match(/^\s*(test|it)\(/gm) ?? []).length]);

// Frontend
const pages = (d) => ls(join(root, "frontend/src/pages", d), ".tsx");
const fe = ["admin", "student", "trainer", "employer", "alumni"].map((d) => [d, pages(d).length]);

const out = [];
out.push(`# Architecture reference (generated)\n\nGenerated by \`backend/scripts/gen-arch-docs.mjs\` from the source tree — re-run it instead of editing this file. Counts are text-pattern matches, not executed code.\n`);
out.push(`## Shape\n- **backend**: Express + Prisma (PostgreSQL); ${routeRows.length} route modules, ${routeRows.reduce((a, r) => a + r.n, 0)} route handlers, ${libs.length} lib modules, ${models.length} models, ${enums.length} enums.\n- **frontend**: React + Vite + Tailwind; pages — ${fe.map(([d, n]) => `${d} ${n}`).join(", ")}.\n- **deploy**: docker-compose (db, backend, frontend/nginx); Moodle and Virtual Business Lab are external systems reached over HTTP.\n`);
out.push(`## Route modules and mount paths (KARC-009)\n| Module | Mount | Handlers |\n|---|---|---|\n${routeRows.map((r) => `| ${r.f} | ${r.mount} | ${r.n} |`).join("\n")}\n`);
out.push(`## Module dependencies — which route modules use each lib (KARC-010)\n| Lib | Used by (route modules) |\n|---|---|\n${libs.map((l) => `| ${l} | ${usedBy[l].length ? usedBy[l].join(", ") : "—"} |`).join("\n")}\n`);
out.push(`## Database models (KARC-011)\n${models.length} models (fields counted by pattern; relations = @relation occurrences).\n\n| Model | Fields | Relations |\n|---|---|---|\n${models.map((m) => `| ${m.name} | ${m.fields} | ${m.rels} |`).join("\n")}\n\nEnums: ${enums.join(", ")}\n`);
out.push(`## Test inventory (KQA-001)\n| File | Tests |\n|---|---|\n${testRows.map(([f, n]) => `| ${f} | ${n} |`).join("\n")}\n\nRun: \`cd backend && npx tsc --noEmit && npm test\` (pure-logic + static tests); \`npm run test:db\` needs a Postgres \`DATABASE_URL\`; \`npm run test:coverage\` for coverage.\n`);
writeFileSync(join(root, "docs/architecture.md"), out.join("\n"));
console.log(`docs/architecture.md written: ${routeRows.length} route modules, ${models.length} models, ${testRows.length} test files`);
